"""Ports for application services; legacy method names preserve adapter compatibility."""
from typing import Protocol, Callable
from datetime import datetime
from .models import Segment, ClassRecord


class AudioInput(Protocol):
    def open(self, selection, callback: Callable, log: Callable): ...


class ITranscriber(Protocol):
    descripcion: str

    def cargar(self) -> None: ...
    def transcribir(self, audio, offset_s: float, contexto: str = "") -> list[Segment]: ...
    def puede_aligerar(self) -> bool: ...
    def aligerar(self) -> None: ...


class IAIProvider(Protocol):
    def generar(self, cfg: dict, clave: str, usuario: str) -> tuple[dict, str]: ...


class IClassRepository(Protocol):
    def crear_clase(self, asignatura: str, nombre: str, modo: str,
                    inicio: datetime | None = None, aula: str = "") -> str: ...
    def leer(self, cid: str) -> ClassRecord: ...
    def actualizar(self, cid: str, **campos) -> dict: ...
    def anadir_segmentos(self, cid: str, segmentos: list[Segment]) -> None: ...
    def cerrar(self, cid: str, fin: datetime | None = None) -> dict: ...
    def listar(self, incluir_segmentos: bool = False) -> list[dict]: ...
    def eliminar(self, cid: str) -> None: ...
